@router.post("/auth/login", response_model=UserResponse)
def login(payload: LoginRequest, response: Response, db: Session = Depends(get_db)) -> UserResponse:
    if not settings.enable_technician_login:
        raise HTTPException(status_code=404, detail="Login is disabled")
    user = db.query(User).filter(User.email == payload.email.lower()).first()
    if not user or not user.is_active or not verify_password(payload.password, user.password_hash):
        raise HTTPException(status_code=401, detail="Invalid email or password")
    session_token = create_session_token(user)
    csrf_token = create_csrf_token()
    secure = settings.app_env in {"production", "preview"}
    response.set_cookie(
        SESSION_COOKIE,
        session_token,
        httponly=True,
        secure=secure,
        samesite="lax",
        max_age=settings.access_session_minutes * 60,
        path="/",
    )
    response.set_cookie(
        CSRF_COOKIE,
        csrf_token,
        httponly=False,
        secure=secure,
        samesite="lax",
        max_age=settings.access_session_minutes * 60,
        path="/",
    )
    return UserResponse(id=user.id, email=user.email, role=user.role)


@router.post("/auth/logout", status_code=204, dependencies=[Depends(require_csrf)])
def logout(response: Response) -> Response:
    response.delete_cookie(SESSION_COOKIE, path="/")
    response.delete_cookie(CSRF_COOKIE, path="/")
    response.status_code = 204
    return response


