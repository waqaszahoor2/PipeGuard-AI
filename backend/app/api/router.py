@router.post(
    "/inspections",
    response_model=InspectionResponse,
    status_code=status.HTTP_201_CREATED,
    dependencies=[Depends(require_csrf)],
)
def create_inspection(
    payload: InspectionCreate,
    request: Request,
    user: CurrentUser = Depends(require_roles("technician", "administrator")),
    db: Session = Depends(get_db),
) -> InspectionRecord:
    record = InspectionRecord(**payload.model_dump())
    record.technician = user.email
    db.add(record)
    db.add(
        ApplicationEvent(
            event_type="inspection_created",
            actor_user_id=user.id,
            request_id=request.state.request_id,
            summary=f"Inspection created for pipeline {payload.pipeline_id}",
        )
    )
    db.commit()
    db.refresh(record)
    return record


@router.patch(
    "/inspections/{inspection_id}",
    response_model=InspectionResponse,
    dependencies=[Depends(require_csrf)],
)
def update_inspection(
    inspection_id: int,
    payload: InspectionUpdate,
    request: Request,
    user: CurrentUser = Depends(require_roles("technician", "administrator")),
    db: Session = Depends(get_db),
) -> InspectionRecord:
    record = db.get(InspectionRecord, inspection_id)
    if not record:
        raise HTTPException(status_code=404, detail="Inspection record not found")
    for key, value in payload.model_dump(exclude_unset=True).items():
        setattr(record, key, value)
    record.updated_at = datetime.now(timezone.utc)
    db.add(
        ApplicationEvent(
            event_type="inspection_updated",
            actor_user_id=user.id,
            request_id=request.state.request_id,
            summary=f"Inspection {inspection_id} updated",
        )
    )
    db.commit()
    db.refresh(record)
    return record


